// Pseudo-localisation: the common industry shortcut. Accent every letter,
// pad the string by ~40% and bracket it, so truncation shows up in English.
(function () {
  const map = { a:"á", b:"ƀ", c:"ç", d:"đ", e:"é", f:"ƒ", g:"ĝ", h:"ĥ", i:"í", j:"ĵ", k:"ķ", l:"ĺ", m:"ḿ", n:"ñ", o:"ő", p:"ṕ", r:"ŕ", s:"š", t:"ŧ", u:"ű", w:"ŵ", y:"ý", z:"ž",
    A:"Á", B:"Ɓ", C:"Ç", D:"Đ", E:"É", F:"Ƒ", G:"Ĝ", H:"Ĥ", I:"Í", J:"Ĵ", K:"Ķ", L:"Ĺ", M:"Ḿ", N:"Ñ", O:"Ő", P:"Ṕ", R:"Ŕ", S:"Š", T:"Ŧ", U:"Ű", W:"Ŵ", Y:"Ý", Z:"Ž" };
  const pseudo = (s) => {
    const body = s.replace(/[A-Za-z]/g, (c) => map[c] || c);
    const pad = "~".repeat(Math.max(1, Math.round(s.length * 0.4)));
    return "[" + body + " " + pad + "]";
  };
  const out = {};
  for (const [k, v] of Object.entries(window.I18N.en)) {
    out[k] = Array.isArray(v) ? v.map(pseudo) : pseudo(v);
  }
  window.I18N.pseudo = out;
})();
